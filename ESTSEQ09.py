#Receba os 2 números inteiros. Calcule e mostre a soma dos quadrados.

#Declarar
n1: int = 0
n2: int = 0
soma: int = 0

#Início
n1 = int(input("Digite um número qualquer inteiro: "))
n2 = int(input("Digite outro número qualquer inteiro: "))
soma = n1**2 + n2**2
print(f"A soma dos quadrados do número {n1} e {n2} é {soma}")

